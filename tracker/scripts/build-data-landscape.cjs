const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const data = require('../content/data-landscape.cjs');
const root = path.resolve(__dirname, '../..');
const check = process.argv.includes('--check');
const ids = new Set(data.entries.map(e => e.id)), groups = new Set(data.groups.map(g => g.id));
assert.equal(ids.size, data.entries.length, 'unique term identities');
assert.equal(groups.size, data.groups.length, 'unique group identities');
for (const e of data.entries) {
  assert.ok(groups.has(e.group), e.id + ' group');
  assert.ok(['tool', 'format', 'concept'].includes(e.kind));
  for (const field of ['name', 'summary', 'what', 'why', 'difference', 'good']) assert.ok(e[field]?.trim(), e.id + ': ' + field);
  assert.ok(e.sources.length && e.related.length, e.id + ': traceable and connected');
  e.sources.forEach(id => assert.ok(data.sources[id], e.id + ': source ' + id));
  e.related.forEach(r => { assert.ok(ids.has(r.to), e.id + ': target ' + r.to); assert.ok(r.label); });
}
for (const source of Object.values(data.sources)) assert.equal(new URL(source.url).protocol, 'https:');
for (const stack of data.stacks) {
  assert.equal(stack.links.length, stack.steps.length - 1);
  [...stack.steps, ...stack.alongside].forEach(id => assert.ok(ids.has(id), stack.id + ': ' + id));
}
data.comparisons.forEach(c => c.ids.forEach(id => assert.ok(ids.has(id))));
const byId = new Map(data.entries.map(e => [e.id, e]));
let md = `# Data landscape: tools, formats and concepts\n\nResearched ${data.reviewed}. ${data.entries.length} core terms in ${data.groups.length} purpose groups, backed by ${Object.keys(data.sources).length} primary sources.\n\nGenerated from \`tracker/content/data-landscape.cjs\`; the interactive reference is the tracker’s **Data map** page (\`#data-map\`).\n\nThis is a role map, not an exhaustive vendor catalog or a compatibility certification. Definitions and distinguishing facts use the linked project documentation, specifications and original architecture writing. Examples and practical cautions are synthesized guidance. Product roles overlap; exact features, prices and connector behavior depend on version and configuration. No paid service is required to use the reference itself.\n\n## How to read it\n\n- Storage keeps bytes. File formats encode values. Table formats manage table state. Catalogs resolve metadata. Engines execute work. Platforms bundle capabilities.\n- Following a labeled relationship tells you how pieces fit; it does not declare a universal migration or deployment recipe.\n- Each entry includes its purpose, distinguishing feature, caveat, connections and primary sources.\n\n## Common mix-ups\n\n`;
for (const c of data.comparisons) md += `### ${c.name}\n\n${c.answer}\n\n`;
md += '## Example stacks\n\n';
for (const s of data.stacks) {
  md += `### ${s.name}\n\n${s.steps.map((id, i) => (i ? ` — **${s.links[i - 1]}** → ` : '') + byId.get(id).name).join('')}\n\n${s.note}\n\n${s.alongsideLabel}: ${s.alongside.map(id => byId.get(id).name).join(', ')}.\n\n`;
}
for (const g of data.groups) {
  md += `## ${g.name}\n\n**${g.question}** ${g.note}\n\n`;
  for (const e of data.entries.filter(e => e.group === g.id)) {
    md += `<a id="${e.id}"></a>\n### ${e.name}\n\n*${e.kind} · ${e.summary}*\n\n**What it is:** ${e.what}\n\n**Why use it:** ${e.why}\n\n**What sets it apart:** ${e.difference}\n\n**Good to know:** ${e.good}\n\n**Connections:**\n\n`;
    md += e.related.map(r => `- ${r.label} → [${byId.get(r.to).name}](#${r.to})`).join('\n') + '\n\n';
    md += '**Sources:** ' + e.sources.map(id => `[${data.sources[id].title}](${data.sources[id].url})`).join(' · ') + '\n\n';
  }
}
const js = '// Generated by scripts/build-data-landscape.cjs; edit content/data-landscape.cjs.\nglobalThis.AELandscapeData = ' + JSON.stringify(data) + ';\n';
for (const [file, content] of [['tracker/ae-tracker/data-landscape-data.js', js], ['docs/reference/data-landscape.md', md]]) {
  const target = path.join(root, file);
  if (check) assert.equal(fs.readFileSync(target, 'utf8'), content, 'Rebuild ' + file);
  else { fs.mkdirSync(path.dirname(target), { recursive: true }); fs.writeFileSync(target, content); }
}
console.log(`${data.entries.length} terms, ${data.groups.length} purpose groups, ${Object.keys(data.sources).length} primary sources; reference ${check ? 'verified' : 'built'}.`);
