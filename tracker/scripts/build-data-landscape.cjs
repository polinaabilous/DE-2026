const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const data = require('../content/data-landscape.cjs');
const root = path.resolve(__dirname, '../..');
const check = process.argv.includes('--check');
const ids = new Set(data.entries.map(e => e.id)), groups = new Set(data.groups.map(g => g.id));
assert.equal(ids.size, data.entries.length, 'unique term identities');
assert.equal(groups.size, data.groups.length, 'unique group identities');
for (const e of data.entries) {
  assert.ok(groups.has(e.group), e.id + ' group');
  assert.ok(['tool', 'format', 'concept'].includes(e.kind));
  for (const field of ['name', 'summary', 'what', 'why', 'difference', 'good']) assert.ok(e[field]?.trim(), e.id + ': ' + field);
  assert.ok(e.sources.length && e.related.length, e.id + ': traceable and connected');
  e.sources.forEach(id => assert.ok(data.sources[id], e.id + ': source ' + id));
  e.related.forEach(r => { assert.ok(ids.has(r.to), e.id + ': target ' + r.to); assert.ok(r.label); });
}
for (const source of Object.values(data.sources)) assert.equal(new URL(source.url).protocol, 'https:');
for (const stack of data.stacks) {
  assert.equal(stack.links.length, stack.steps.length - 1);
  [...stack.steps, ...stack.alongside].forEach(id => assert.ok(ids.has(id), stack.id + ': ' + id));
}
data.comparisons.forEach(c => c.ids.forEach(id => assert.ok(ids.has(id))));
const js = '// Generated by scripts/build-data-landscape.cjs; edit content/data-landscape.cjs.\nglobalThis.AELandscapeData = ' + JSON.stringify(data) + ';\n';
const target = path.join(root, 'tracker/de-tracker/data-landscape-data.js');
if (check) assert.equal(fs.readFileSync(target, 'utf8'), js, 'Rebuild data-landscape-data.js');
else fs.writeFileSync(target, js);
console.log(`${data.entries.length} terms, ${data.groups.length} purpose groups, ${Object.keys(data.sources).length} primary sources; reference ${check ? 'verified' : 'built'}.`);
